"""Build the compatibility version of the site (works in browsers without scroll-driven animation).

    python3 scripts/compat-build.py [target-dir]      # default: "." = patch the site root in place

What it does, and nothing else:
  * copies the site into the target directory (skipped when the target is ".")
  * appends a generated, marker-delimited block to styles.css:
      - a copy of every scroll-driven rule, gated to <html class="sd-poly"> (the browser's own @supports blocks are
        left untouched, so Chrome and Safari 26 run exactly what they ran before). In the copy, animation-range is
        stored as --sd-range and each rule is paused with a 1s duration; scripts/sd.js then sets each animation's
        time from the scroll position.
      - the header rules for modes without native scroll timelines
      - the static layout (the plain page) used when nothing animated can run
  * adds the mode-picking script to the top of <head> in index.html and loads assets/sd.js at the end of <body>.
Idempotent: re-running replaces the generated block and the injected tags."""
import re, shutil, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = sys.argv[1] if len(sys.argv) > 1 else '.'
T = os.path.join(ROOT, target)
inplace = os.path.abspath(T) == ROOT

HEAD_START, HEAD_END = '<!-- SD-HEAD-START -->', '<!-- SD-HEAD-END -->'
BODY_START, BODY_END = '<!-- SD-BODY-START -->', '<!-- SD-BODY-END -->'
CSS_START, CSS_END = '/* SD-COMPAT-START (generated by scripts/compat-build.py) */', '/* SD-COMPAT-END */'

HEAD = '''<script>
/* Pick how the drawing runs: native scroll-driven animation, the scripted version, or the plain static page. */
(function () {
  var cl = document.documentElement.classList;
  try {
    var reduce = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;
    var ok = !!(window.CSS && CSS.supports);
    var native = ok && CSS.supports('animation-timeline', 'view()') && CSS.supports('animation-timeline', 'scroll()');
    var poly = ok && 'getAnimations' in Element.prototype && !!CSS.registerProperty &&
      CSS.supports('offset-path', 'path("M0 0")') && CSS.supports('animation-play-state', 'paused');
    var m = reduce ? 'static' : native ? 'native' : poly ? 'poly' : 'static';
    // the scripted mode starts as the safe static page and switches on only once assets/sd.js has really built it
    if (m === 'poly') { cl.add('sd-static'); cl.add('sd-want-poly'); } else cl.add('sd-' + m);
  } catch (e) { cl.add('sd-static'); }
})();
</script>'''
BODY = '<script src="./assets/sd.js" defer></script>'


# ---------------------------------------------------------------- css helpers
def match_brace(s, i):
    """index of the } that closes the { at s[i]"""
    d = 0
    for j in range(i, len(s)):
        if s[j] == '{': d += 1
        elif s[j] == '}':
            d -= 1
            if d == 0: return j
    raise ValueError('unbalanced braces')


def supports_blocks(css, cond):
    """inner text of every @supports <cond> { ... } block"""
    out, pos = [], 0
    key = '@supports ' + cond
    while True:
        i = css.find(key, pos)
        if i < 0: return out
        b = css.index('{', i)
        e = match_brace(css, b)
        out.append(css[b + 1:e]); pos = e + 1


def split_rules(inner):
    """[(comment, selector, body)] for a flat list of rules"""
    rules, i = [], 0
    while i < len(inner):
        m = re.match(r'\s*', inner[i:]); i += m.end()
        if i >= len(inner): break
        if inner.startswith('/*', i):
            j = inner.index('*/', i) + 2
            rules.append(('c', inner[i:j], None)); i = j; continue
        b = inner.index('{', i); e = match_brace(inner, b)
        rules.append(('r', inner[i:b].strip(), inner[b + 1:e])); i = e + 1
    return rules


# Animations that only change a custom property are driven from sd.js as inline custom properties instead:
# Firefox does not re-read var() inside the keyframes of other animations when such a property is animated.
VARS = {'calm': ('--amp', '1', '0'), 'calm-m': ('--amp', '0.5', '0'), 'walk-on': ('--walk', '0', '1'), 'pace-on': ('--pace', '0', '1')}


def split_vars(body):
    mn = re.search(r'animation-name:\s*([^;]+);', body)
    if not mn: return body
    names = [n.strip() for n in mn.group(1).split(',')]
    if not any(n in VARS for n in names): return body
    mr = re.search(r'--sd-range:\s*([^;]+);', body)
    ranges = [r.strip() for r in mr.group(1).split(',')] if mr else None
    keep_n, keep_r, vars_ = [], [], []
    for i, n in enumerate(names):
        if n in VARS:
            if ranges is not None:
                prop, a, b = VARS[n]; vars_.append('%s %s %s %s' % (prop, a, b, ranges[i]))
        else:
            keep_n.append(n)
            if ranges is not None: keep_r.append(ranges[i])
    body = body.replace(mn.group(0), 'animation-name: %s;' % ', '.join(keep_n))
    if mr:
        body = body.replace(mr.group(0), '--sd-range: %s;' % ', '.join(keep_r) + ('\n      --sd-vars: %s;' % ', '.join(vars_) if vars_ else ''))
    return body


def to_poly(inner):
    out = []
    for kind, sel, body in split_rules(inner):
        if kind == 'c':
            continue
        had_timeline = 'animation-timeline' in body
        body = re.sub(r'animation-timeline:[^;]*;', '', body)
        body = re.sub(r'view-timeline-[a-z]+:[^;]*;', '', body)
        had_range = 'animation-range:' in body
        body = re.sub(r'animation-range:([^;]*);', r'--sd-range:\1;', body)
        body = split_vars(body)
        if had_timeline or had_range:
            body = body.rstrip() + '\n      animation-duration: 1s; animation-delay: 0s; animation-iteration-count: 1; animation-play-state: paused;\n    '
        if not body.strip(' \n;'):
            continue   # e.g. .flow { view-timeline-name... } leaves nothing
        sels = ', '.join('html.sd-poly ' + s.strip() for s in sel.split(','))
        out.append('  %s {%s}' % (sels, body))
    return '\n'.join(out)


