def build_css(css):
    css = re.sub(re.escape(CSS_START) + r'.*?' + re.escape(CSS_END) + r'\n?', '', css, flags=re.S).rstrip('\n') + '\n'
    # the old half-built fallback (lines drawn whole, shapes solid) must not leak into the scripted mode;
    # it never applied in browsers that support scroll timelines, so this changes nothing for them
    css = css.replace('@supports not (animation-timeline: view())', '@media not all')
    desktop, phone = None, None
    for k, inner in enumerate(supports_blocks(css, '(animation-timeline: view())')):
        if '.line-m' in inner and '.l1' in inner and desktop is not None: phone = inner
        elif '.lane' in inner and phone is None and desktop is None: desktop = inner
        else: phone = inner
    assert desktop and phone, 'could not find the two view() blocks'
    block = [CSS_START,
             '@property --sd-range { syntax: "*"; inherits: false; }',
             '@property --sd-vars { syntax: "*"; inherits: false; }',
             '@keyframes sd-probe { to { opacity: 0.02; } }',
             '/* scroll-driven rules, scripted (html.sd-poly); animation-range is stored as --sd-range */',
             to_poly(desktop),
             '@media (max-width: 900px) and (max-aspect-ratio: 1/1) {',
             '  html.sd-poly .trail-fade-d { display: none; }   /* the desktop fade must not leak onto phones */',
             to_poly(phone),
             '}',
             STATIC, CSS_END, '']
    return css + '\n'.join(block)


def build_html(h):
    h = re.sub(r'\n[ \t]*' + re.escape(HEAD_START) + r'.*?' + re.escape(HEAD_END), '', h, flags=re.S)
    h = re.sub(re.escape(BODY_START) + r'.*?' + re.escape(BODY_END) + r'\n?', '', h, flags=re.S)
    vp = '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">'
    assert vp in h, 'viewport meta not found'
    h = h.replace(vp, vp + '\n  ' + HEAD_START + '\n' + HEAD + '\n  ' + HEAD_END, 1)   # after charset + viewport
    h = h.replace('</body>', BODY_START + '\n' + BODY + '\n' + BODY_END + '\n</body>', 1)
    return h


def main():
    if not inplace:
        if os.path.exists(T): shutil.rmtree(T)
        os.makedirs(T)
        for f in ('index.html', 'privacy.html', 'terms.html', 'styles.css', 'favicon.ico', 'site.webmanifest'):
            shutil.copy(os.path.join(ROOT, f), T)
        shutil.copytree(os.path.join(ROOT, 'assets'), os.path.join(T, 'assets'))
    shutil.copy(os.path.join(ROOT, 'scripts', 'sd.js'), os.path.join(T, 'assets', 'sd.js'))
    for f, fn in (('styles.css', build_css), ('index.html', build_html)):
        p = os.path.join(T, f)
        with open(p) as fh: s = fh.read()
        with open(p, 'w') as fh: fh.write(fn(s))
    print('built', target)


main()
